#!/usr/bin/env node
// Copies shared/*.mjs into each skill that uses it, so every skill folder works on its own when copied.
// `--check` exits 1 if any copy is out of date (run in CI and tests).
import { mkdirSync, readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(fileURLToPath(new URL('..', import.meta.url)));
export const TARGETS = ['backend-execute', 'provider-connect', 'backend-planner'];
const HEADER = '// GENERATED by scripts/sync-shared.mjs from shared/. Do not edit here.\n';

/** @param {boolean} check @returns {string[]} stale or written files */
export function sync(check) {
  const files = readdirSync(join(ROOT, 'shared')).filter((f) => f.endsWith('.mjs'));
  const changed = [];
  for (const skill of TARGETS) {
    const dir = join(ROOT, 'skills', skill, 'scripts', 'shared');
    for (const f of files) {
      const want = HEADER + readFileSync(join(ROOT, 'shared', f), 'utf8');
      const target = join(dir, f);
      if (existsSync(target) && readFileSync(target, 'utf8') === want) continue;
      changed.push(`skills/${skill}/scripts/shared/${f}`);
      if (!check) {
        mkdirSync(dir, { recursive: true });
        writeFileSync(target, want);
      }
    }
  }
  return changed;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  const changed = sync(check);
  if (check && changed.length) {
    console.error(`Out of date (run npm run sync:shared):\n  ${changed.join('\n  ')}`);
    process.exit(1);
  }
  console.log(changed.length ? `${check ? 'stale' : 'updated'}: ${changed.join(', ')}` : 'shared copies up to date');
}
